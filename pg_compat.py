"""PostgreSQL backend that the app can use through its existing sqlite3 calls.

WHY THIS EXISTS
===============
The trading engine (paper_trading_app_TV.py) is deliberately frozen: it is the
audited money-handling code. Every one of its SQL calls is written for sqlite3.
Rather than rewrite that file for a hosted database, this module is a DB-API
2.0 shim that *is* `sqlite3` as far as the app is concerned, but speaks
PostgreSQL underneath:

    import pg_compat
    pg_compat.install()      # only when PAPER_TRADER_DB_URL is set
    import sqlite3           # <- now this is the shim

`install()` rebinds sys.modules["sqlite3"], so every later `import sqlite3`
(the frozen engine, engine.py, accounts.py, app_web.py) gets the shim without
a single edit to any of them. With no PAPER_TRADER_DB_URL set, nothing here is
imported and the app keeps using real SQLite exactly as before.

WHAT IT TRANSLATES (measured from the actual code, not guessed)
==============================================================
  ? placeholders           -> %s, skipping 'literals' and -- /* comments */
  literal % in SQL         -> %% when parameters are present (psycopg2 rule)
  PRAGMA foreign_keys=ON   -> ignored: PostgreSQL enforces FKs natively
  PRAGMA journal_mode=WAL  -> ignored (with synchronous/busy_timeout)
  PRAGMA table_info(t)     -> emulated from information_schema, same columns
  INSERT OR REPLACE        -> INSERT ... ON CONFLICT (pk) DO UPDATE
  cursor.lastrowid         -> appends RETURNING id to the INSERT
  INTEGER PRIMARY KEY AUTOINCREMENT -> ... GENERATED BY DEFAULT AS IDENTITY
  REAL                     -> DOUBLE PRECISION (DDL only)
  COLLATE NOCASE           -> lower(...) in queries, dropped in DDL
  sqlite3.Error & friends  -> mapped from psycopg2's exception classes

It also survives the thing that actually breaks long-lived hosted databases:
a dropped or suspended connection. Reads and the first statement of a
connection are retried once on a fresh connection; a connection with
uncommitted writes is never silently retried, so a statement cannot be
applied twice.
"""

