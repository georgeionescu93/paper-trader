class Cursor:
    def __init__(self, conn):
        self._conn = conn
        self._cur = conn._conn.cursor()
        self._noop_rows = []
        self.lastrowid = None
        self.rowcount = -1
        self.description = None
        self.arraysize = 1
        self._closed = False

    # -- internals ---------------------------------------------------------
    def _run(self, statement, params):
        sql = statement.sql
        if statement.kind == "table_info":
            self._cur.execute(TABLE_INFO_SQL,
                              (statement.table, statement.table))
            return
        if statement.kind == "noop":
            # PostgreSQL always writes WAL and enforces foreign keys; only the
            # caller's expectation of a row needs satisfying.
            self._noop_rows = [("wal",)] if statement.note == "delete" else []
            self.description = [("journal_mode",)]
            self.rowcount = 0
            return
        if statement.kind == "replace":
            sql = self._replace_sql(statement)
        elif statement.kind == "write":
            sql = self._maybe_returning(statement)
        if params is None:
            self._cur.execute(sql)
        else:
            self._cur.execute(sql, params)
        self.rowcount = self._cur.rowcount
        self.description = self._cur.description
        if statement.kind == "write" and self.description:
            row = self._cur.fetchone()
            self.lastrowid = row[0] if row else None
            self.description = None
            if self.rowcount in (-1, None):
                self.rowcount = 1

    def _replace_sql(self, statement):
        """INSERT OR REPLACE -> INSERT ... ON CONFLICT (pk) DO UPDATE."""
        pks = self._conn._primary_key(statement.table)
        if not pks:
            raise NotSupportedError(
                f"INSERT OR REPLACE needs a primary key; "
                f"table {statement.table!r} has none")
        cols = statement.columns
        target = ", ".join(pks)
        updatable = [c for c in cols if c not in pks]
        if updatable:
            assignments = ", ".join(f"{c} = EXCLUDED.{c}" for c in updatable)
            tail = f" ON CONFLICT ({target}) DO UPDATE SET {assignments}"
        else:
            tail = f" ON CONFLICT ({target}) DO NOTHING"
        return statement.sql + tail

    def _maybe_returning(self, statement):
        """cursor.lastrowid is emulated with RETURNING id, when the table has
        one. Tables keyed on something else (settings, risk_state) get nothing,
        exactly like SQLite, where lastrowid would also be meaningless."""
        if _RETURNING.search(statement.sql):
            return statement.sql
        if not self._conn._has_column(statement.table, "id"):
            return statement.sql
        return statement.sql + " RETURNING id"

    # -- DB-API ------------------------------------------------------------
    def execute(self, sql, params=None):
        statement = translate(sql, params)
        if statement.params is None:
            statement.params = params
        was_dirty = self._conn._dirty
        self._conn._note_write(statement.kind)
        try:
            self._run(statement, statement.params)
        except Exception as exc:                            # noqa: BLE001
            mapped = _map_exc(exc)
            # A hosted database drops idle connections (Neon suspends after a
            # few minutes). Retry once on a fresh connection - but only when
            # nothing is pending, so a statement can never be applied twice.
            safe = statement.kind in ("select", "table_info", "noop") \
                or not was_dirty
            if isinstance(mapped, OperationalError) and safe \
                    and _retryable(exc):
                try:
                    self._conn._reconnect()
                    self._cur = self._conn._conn.cursor()
                    self._run(statement, statement.params)
                    return self
                except Exception as retry_exc:              # noqa: BLE001
                    raise _map_exc(retry_exc) from retry_exc
            raise mapped from exc
        return self

    def executemany(self, sql, seq_of_params):
        for params in seq_of_params:
            self.execute(sql, params)
        return self

    def executescript(self, script):
        for part in filter(None, (s.strip() for s in script.split(";"))):
            self.execute(part)
        return self

    def fetchone(self):
        if self._noop_rows:
            return self._noop_rows[0]
        if self._cur.description is None:
            return None
        return self._cur.fetchone()

    def fetchmany(self, size=None):
        if self._noop_rows:
            rows, self._noop_rows = self._noop_rows, []
            return rows
        if self._cur.description is None:
            return []
        return self._cur.fetchmany(size or self.arraysize)

    def fetchall(self):
        if self._noop_rows:
            rows, self._noop_rows = self._noop_rows, []
            return rows
        if self._cur.description is None:
            return []
        return self._cur.fetchall()

    def close(self):
        if not self._closed:
            self._closed = True
            try:
                self._cur.close()
            except Exception:                               # noqa: BLE001
                pass

    def __iter__(self):
        return iter(self.fetchall())


class Connection:
    def __init__(self, dsn, timeout=10, kwargs=None):
        self._dsn = dsn
        self._lock = threading.RLock()
        self._pk_cache = {}
        self._col_cache = {}
        self._dirty = False
        self._closed = False
        self._connect(timeout, kwargs or {})

    # -- internals ---------------------------------------------------------
    def _connect(self, timeout, kwargs):
        driver = _driver()
        params = dict(kwargs)
        params.setdefault("connect_timeout", max(1, int(timeout or 10)))
        params.setdefault("application_name", "paper-trader")
        last = None
        for attempt, delay in enumerate((0.0, 0.5, 1.5, 3.0)):
            if delay:
                time.sleep(delay)
            try:
                self._conn = driver.connect(self._dsn, **params)
                self._dirty = False
                return
            except Exception as exc:                        # noqa: BLE001
                last = exc
                if not _retryable(exc) or attempt == 3:
                    break
        raise _map_exc(last)

    def _reconnect(self, timeout=10):
        try:
            self._conn.close()
        except Exception:                                   # noqa: BLE001
            pass
        self._connect(timeout, {})

    def _primary_key(self, table):
        if table not in self._pk_cache:
            cur = self._conn.cursor()
            cur.execute(TABLE_PK_SQL, (table,))
            self._pk_cache[table] = [r[0] for r in cur.fetchall()]
            cur.close()
        return self._pk_cache[table]

    def _has_column(self, table, column):
        key = (table, column)
        if key not in self._col_cache:
            cur = self._conn.cursor()
            cur.execute(HAS_COLUMN_SQL, (table, column))
            self._col_cache[key] = cur.fetchone() is not None
            cur.close()
        return self._col_cache[key]

    def _note_write(self, kind):
        if kind in ("write", "replace", "ddl"):
            self._dirty = True

    # -- DB-API ------------------------------------------------------------
    def cursor(self):
        return Cursor(self)

    def execute(self, sql, params=None):
        return self.cursor().execute(sql, params)

    def executemany(self, sql, seq_of_params):
        return self.cursor().executemany(sql, seq_of_params)

    def executescript(self, script):
        return self.cursor().executescript(script)

    def commit(self):
        self._conn.commit()
        self._dirty = False

    def rollback(self):
        self._conn.rollback()
        self._dirty = False

    def close(self):
        if self._closed:
            return
        self._closed = True
        try:
            if self._dirty:
                self._conn.rollback()
        except Exception:                                   # noqa: BLE001
            pass
        try:
            self._conn.close()
        except Exception:                                   # noqa: BLE001
            pass

    # psycopg2-style aliases, harmless to provide
    def set_session(self, **kwargs):                        # pragma: no cover
        return None

    @property
    def autocommit(self):
        return False

    def __enter__(self):
        return self

    def __exit__(self, *exc_info):
        if exc_info and exc_info[0]:
            self.rollback()
        else:
            self.commit()


# ---------------------------------------------------------------------------
# exception mapping
# ---------------------------------------------------------------------------
def _map_exc(exc):
    if isinstance(exc, Error):
        return exc
    driver = _DRIVER
    if driver is not None:
        table = (
            (getattr(driver, "IntegrityError", None), IntegrityError),
            (getattr(driver, "OperationalError", None), OperationalError),
            (getattr(driver, "InterfaceError", None), InterfaceError),
            (getattr(driver, "ProgrammingError", None), ProgrammingError),
            (getattr(driver, "DataError", None), DataError),
            (getattr(driver, "InternalError", None), InternalError),
            (getattr(driver, "NotSupportedError", None), NotSupportedError),
            (getattr(driver, "DatabaseError", None), DatabaseError),
            (getattr(driver, "Error", None), Error),
        )
        for source, target in table:
            if source is not None and isinstance(exc, source):
                return target(str(exc).strip())
    return OperationalError(str(exc).strip())


_RETRY_HINTS = (
    "server closed the connection",
    "connection already closed",
    "connection has been closed",
    "terminating connection",
    "could not connect",
    "connection refused",
    "connection reset",
    "timeout expired",
    "the database system is starting up",
    "ssl connection has been closed",
)


def _retryable(exc):
    text = str(exc).lower()
    return any(hint in text for hint in _RETRY_HINTS)


# ---------------------------------------------------------------------------
# public entry points
# ---------------------------------------------------------------------------
def resolve_url():
    for name in URL_ENV_VARS:
        value = (os.environ.get(name) or "").strip()
        if value:
            return value
    return ""


def connect(database=None, timeout=10, **kwargs):
    """Same signature as sqlite3.connect; `database` is ignored on purpose.

    The frozen engine calls sqlite3.connect(DB_FILE, timeout=10). Which file
    it thinks it is opening no longer matters: the URL decides.
    """
    url = resolve_url()
    if not url:
        raise InterfaceError(
            "pg_compat is active but no database URL is set. Define "
            + " or ".join(URL_ENV_VARS) + " (a postgres:// connection string).")
    return Connection(url, timeout=timeout, kwargs=kwargs)


_INSTALLED = False


def install(verbose=True):
    """Rebinds `sqlite3` to this module for the rest of the process."""
    global _INSTALLED
    if _INSTALLED:
        return True
    sys.modules["sqlite3"] = sys.modules[__name__]
    _INSTALLED = True
    if verbose:
        url = resolve_url()
        host = re.sub(r"://[^@]*@", "://***@", url)
        print(f"  Database : PostgreSQL via pg_compat  ({host})")
    return True


def is_installed():
    return _INSTALLED


def auto_install(verbose=True):
    """Installs only when a PostgreSQL URL is configured."""
    url = resolve_url()
    if url.startswith(SCHEME) or (url and "://" in url
                                  and not url.startswith("sqlite")):
        return install(verbose=verbose)
    return False
