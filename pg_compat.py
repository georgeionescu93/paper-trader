# SQL translation
# ---------------------------------------------------------------------------
_AUTOINC = re.compile(r"\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b", re.I)
_AUTOINC_LOOSE = re.compile(r"\bAUTOINCREMENT\b", re.I)
_REAL_TYPE = re.compile(r"\bREAL\b", re.I)
_NOCASE = re.compile(r"(\?|%s|\w+(?:\.\w+)?)\s+COLLATE\s+NOCASE", re.I)
_NOCASE_PLAIN = re.compile(r"\s+COLLATE\s+NOCASE", re.I)
_TABLE_INFO = re.compile(
    r"PRAGMA\s+table_info\s*\(\s*['\"]?([A-Za-z_][A-Za-z0-9_]*)['\"]?\s*\)",
    re.I)
_PRAGMA = re.compile(r"^\s*PRAGMA\b", re.I)
_DDL = re.compile(r"^\s*(CREATE|ALTER|DROP)\b", re.I)
_INSERT_REPLACE = re.compile(
    r"^\s*INSERT\s+OR\s+REPLACE\s+INTO\s+([A-Za-z_][A-Za-z0-9_]*)\s*"
    r"\(([^)]*)\)\s*VALUES\s*\((.*)\)\s*$", re.I | re.S)
_INSERT = re.compile(
    r"^\s*INSERT\s+INTO\s+([A-Za-z_][A-Za-z0-9_]*)\s*\(([^)]*)\)\s*VALUES\b",
    re.I)
_RETURNING = re.compile(r"\bRETURNING\b", re.I)
_PRAGMA_JOURNAL = re.compile(r"PRAGMA\s+journal_mode", re.I)


def _scan(sql, escape_percent=False):
    """Walks SQL outside of literals and comments, in one pass.

    - '?' becomes '%s', PostgreSQL's placeholder. The '%s' this function emits
      is never re-escaped.
    - when parameters are present, a literal '%' becomes '%%' first, because
      psycopg2 %-interpolates the whole statement (the classic psycopg2 trap).

    Inside single-quoted strings, double-quoted identifiers and comments a '?'
    is literal text, not a parameter marker - translating it would corrupt the
    query. Returns (out_text, placeholders_seen).
    """
    out = []
    i = 0
    n = len(sql)
    seen = 0
    while i < n:
        ch = sql[i]
        if ch == "'" or ch == '"':
            quote = ch
            out.append(ch)
            i += 1
            while i < n:
                c = sql[i]
                if c == "%" and escape_percent:
                    out.append("%%")
                    i += 1
                    continue
                out.append(c)
                if c == quote:
                    if i + 1 < n and sql[i + 1] == quote:   # '' escape
                        out.append(sql[i + 1])
                        i += 2
                        continue
                    i += 1
                    break
                i += 1
            continue
        if ch == "-" and sql.startswith("--", i):
            end = sql.find("\n", i)
            end = n if end < 0 else end
            chunk = sql[i:end]
            out.append(chunk.replace("%", "%%") if escape_percent else chunk)
            i = end
            continue
        if ch == "/" and sql.startswith("/*", i):
            end = sql.find("*/", i + 2)
            end = n if end < 0 else end + 2
            chunk = sql[i:end]
            out.append(chunk.replace("%", "%%") if escape_percent else chunk)
            i = end
            continue
        if ch == "?":
            out.append("%s")
            seen += 1
            i += 1
            continue
        if ch == "%" and escape_percent:
            out.append("%%")
            i += 1
            continue
        out.append(ch)
        i += 1
    return "".join(out), seen


class Statement:
    """A translated statement plus what the cursor must do about it."""

    __slots__ = ("kind", "sql", "table", "columns", "params", "note")

    def __init__(self, kind, sql, table=None, columns=None, params=None,
                 note=""):
        self.kind = kind          # select|write|ddl|table_info|noop|replace
        self.sql = sql
        self.table = table
        self.columns = columns or []
        self.params = params
        self.note = note

    def __repr__(self):                                     # pragma: no cover
        return f"Statement({self.kind!r}, {self.sql!r}, table={self.table!r})"


# ---------------------------------------------------------------------------
# SQLite's two-argument scalar MAX() / MIN()
# ---------------------------------------------------------------------------
# SQLite defines MAX(a, b) and MIN(a, b) as scalar functions that return the
# larger / smaller argument. PostgreSQL has no such function: there MAX and MIN
# are aggregates only, and the scalar form is spelled GREATEST() / LEAST(). So
# `MAX(COALESCE(stop_loss, ?), ?)` fails on Postgres with
#     function max(numeric, numeric) does not exist
# That exact statement is how a Trading Mode entry records its protective stop,
# in both engine.py and paper_trading_app_TV.py. Because the failure was being
# swallowed by a bare `except sqlite3.Error: return False`, every hosted entry
# silently failed to book while every scan and recommendation looked healthy.
_SCALAR_FUNC = re.compile(r"\b(MAX|MIN)\s*\(", re.I)


def _scalar_maxmin(sql):
    """Two-argument MAX()/MIN() -> GREATEST()/LEAST(); aggregates untouched."""
    out = []
    i = 0
    while i < len(sql):
        match = _SCALAR_FUNC.search(sql, i)
        if not match:
            out.append(sql[i:])
            break
        out.append(sql[i:match.end()])
        start = match.end()                  # just past the opening paren
        depth, comma, j = 1, False, start
        while j < len(sql) and depth:
            ch = sql[j]
            if ch == "(":
                depth += 1
            elif ch == ")":
                depth -= 1
                if not depth:
                    break
            elif ch == "," and depth == 1:
                comma = True
            j += 1
        if depth or not comma:               # single argument: an aggregate
            i = match.end()
            continue
        name = "GREATEST" if match.group(1).upper() == "MAX" else "LEAST"
        out[-1] = sql[i:match.start()] + name + "("
        out.append(sql[start:j] + ")")
        i = j + 1
    return "".join(out)


def translate(sql, params=None):
    """Pure translation: no database access, so it is unit-testable."""
    if not isinstance(sql, str):
        raise ProgrammingError("SQL statement must be a string")

    match = _TABLE_INFO.search(sql)
    if match:
        return Statement("table_info", sql, table=match.group(1),
                         params=[])

    if _PRAGMA.match(sql):
        if _PRAGMA_JOURNAL.search(sql):
            # Callers only care that it did not raise; report "delete" politely.
            return Statement("noop", sql, params=[], note="delete")
        return Statement("noop", sql, params=[])

    if _DDL.match(sql):
        text = _AUTOINC.sub(
            "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", sql)
        text = _AUTOINC_LOOSE.sub("", text)
        if re.match(r"^\s*CREATE\s+TABLE", text, re.I):
            text = _REAL_TYPE.sub("DOUBLE PRECISION", text)
        text = _NOCASE_PLAIN.sub("", text)
        return Statement("ddl", text, params=params)

    # COLLATE NOCASE binds tighter than '=', so `email = ? COLLATE NOCASE`
    # means a case-insensitive comparison. lower(...) is the portable form.
    nocase = _scalar_maxmin(_NOCASE.sub(r"lower(\1)", sql))
    text, seen = _scan(nocase, escape_percent=params is not None)
    if params is not None and seen == 0:
        # Parameters with no placeholder: they will not be interpolated, so a
        # literal % must stay single.
        text, seen = _scan(nocase, escape_percent=False)

    replace = _INSERT_REPLACE.match(text)
    if replace:
        table = replace.group(1)
        columns = [c.strip().strip('"') for c in replace.group(2).split(",")]
        return Statement("replace", text, table=table, columns=columns,
                         params=params)

    insert = _INSERT.match(text)
    if insert:
        return Statement("write", text, table=insert.group(1), params=params)

    kind = "select" if re.match(r"^\s*(SELECT|WITH|VALUES|SHOW)\b", text, re.I) \
        else "write"
    return Statement(kind, text, params=params)


# ---------------------------------------------------------------------------
# Emulated PRAGMA table_info, in sqlite3's exact column order
# ---------------------------------------------------------------------------
TABLE_INFO_SQL = """
SELECT c.ordinal_position - 1                       AS cid,
       c.column_name,
       CASE
         WHEN c.data_type IN ('integer', 'bigint', 'smallint') THEN 'INTEGER'
         WHEN c.data_type IN ('double precision', 'real', 'numeric') THEN 'REAL'
         WHEN c.data_type = 'boolean' THEN 'INTEGER'
         ELSE 'TEXT'
       END                                          AS type,
       CASE WHEN c.is_nullable = 'NO' THEN 1 ELSE 0 END AS notnull,
       c.column_default                             AS dflt_value,
       CASE WHEN pk.column_name IS NOT NULL THEN 1 ELSE 0 END AS pk
  FROM information_schema.columns c
  LEFT JOIN (
        SELECT kcu.column_name
          FROM information_schema.table_constraints tc
          JOIN information_schema.key_column_usage kcu
            ON kcu.constraint_name = tc.constraint_name
           AND kcu.table_schema = tc.table_schema
         WHERE tc.constraint_type = 'PRIMARY KEY'
           AND tc.table_name = %s
       ) pk ON pk.column_name = c.column_name
 WHERE c.table_name = %s
 ORDER BY c.ordinal_position
"""

TABLE_PK_SQL = """
SELECT kcu.column_name
  FROM information_schema.table_constraints tc
  JOIN information_schema.key_column_usage kcu
    ON kcu.constraint_name = tc.constraint_name
   AND kcu.table_schema = tc.table_schema
 WHERE tc.constraint_type = 'PRIMARY KEY'
   AND tc.table_name = %s
 ORDER BY kcu.ordinal_position
"""

HAS_COLUMN_SQL = """
SELECT 1 FROM information_schema.columns
 WHERE table_name = %s AND column_name = %s
"""


