class Row(tuple):
    """Minimal stand-in for sqlite3.Row (the app indexes rows positionally,
    so this exists only so nothing explodes if some future code asks for it)."""

    def __new__(cls, values, keys=None):
        obj = super().__new__(cls, values)
        obj._keys = list(keys or [])
        return obj

    def keys(self):
        return list(self._keys)

    def __getitem__(self, item):
        if isinstance(item, str):
            return tuple.__getitem__(self, self._keys.index(item))
        return tuple.__getitem__(self, item)

    def get(self, key, default=None):
        try:
            return self[key]
        except (ValueError, IndexError):
            return default


def _driver():
    """psycopg2, imported on demand so unit tests can substitute a fake."""
    if _DRIVER is not None:
        return _DRIVER
    try:
        import psycopg2                                    # noqa: PLC0415
        import psycopg2.extensions                          # noqa: PLC0415
    except ImportError as exc:                              # pragma: no cover
        raise InterfaceError(
            "PostgreSQL backend selected (PAPER_TRADER_DB_URL is set) but "
            "psycopg2 is not installed. Run: pip install psycopg2-binary"
        ) from exc
    return psycopg2


